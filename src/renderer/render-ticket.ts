/**
 * Номера отрисовок дерева: ответ устаревшей отбрасывается. Опрос git status («только если изменилось») номера не занимает:
 * его пустой ответ «ничего не изменилось» не должен отменять отрисовку клика, начатую раньше, - иначе обе отбрасываются,
 * а дерево остаётся прежним до следующего изменения в git.
 */
export class RenderTickets {
  private current = 0;

  /** Номер для отрисовки; опрос берёт текущий, остальные - следующий. */
  take(poll: boolean): number {
    return poll ? this.current : ++this.current;
  }

  /** Ответ с этим номером ещё нужен. */
  valid(ticket: number): boolean {
    return ticket === this.current;
  }
}
